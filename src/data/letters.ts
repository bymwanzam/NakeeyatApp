/**
 * The 28 letters of the Arabic alphabet.
 *
 * `connects` means the letter joins to the letter that FOLLOWS it. The six
 * letters ا د ذ ر ز و never do, which is why words like  دَجَاجَة  break
 * into visual chunks. The forms below are written with the tatweel joiner (ـ)
 * so each one renders in isolation exactly as it looks inside a word.
 */
export type Letter = {
  id: string
  /** Isolated form — the letter on its own. */
  char: string
  /** Name of the letter in Arabic, fully voweled. */
  nameAr: string
  /** Name of the letter in English. */
  nameEn: string
  /** Joins to the following letter? */
  connects: boolean
  /** Shapes the letter takes by position in a word. */
  forms: { initial: string; medial: string; final: string }
  /** Plain-English hint for how the letter sounds. */
  soundEn: string
  /** A familiar word that starts with this letter. */
  word: { ar: string; translit: string; en: string }
}

